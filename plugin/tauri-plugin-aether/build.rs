const COMMANDS_DIR: &str = "permissions/autogenerated/commands";
const SETS_DIR: &str = "permissions/autogenerated/sets";

fn main() -> io::Result<()> {
    // Regenerated every build so toggling a feature off leaves no stale permission behind.
    for dir in [COMMANDS_DIR, SETS_DIR] {
        if let Err(error) = fs::remove_dir_all(dir)
            && error.kind() != io::ErrorKind::NotFound
        {
            return Err(error);
        }
    }
    fs::create_dir_all(SETS_DIR)?;
    let mut commands = Vec::new();
    for (set, feature, set_commands) in FEATURES {
        if !feature.is_empty() && std::env::var_os(feature).is_none() {
            continue;
        }
        commands.extend_from_slice(set_commands);
        let permissions = set_commands
            .iter()
            .map(|command| format!("\"allow-{}\"", command.replace('_', "-")))
            .collect::<Vec<_>>()
            .join(", ");
        fs::write(
            format!("{SETS_DIR}/{set}.toml"),
            format!(
                "# Automatically generated by build.rs - DO NOT EDIT!\n\n[[set]]\nidentifier = \"{set}\"\ndescription = \"Commands of the `{set}` set.\"\npermissions = [{permissions}]\n"
            ),
        )?;
    }
    tauri_plugin::Builder::new(&commands).build();
    embed_test_manifest()
}

/// Test binaries link tauri, which needs Common Controls v6 on Windows; without this
/// manifest they die with `STATUS_ENTRYPOINT_NOT_FOUND` (tauri does the same for its tests).
fn embed_test_manifest() -> io::Result<()> {
    if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() != Ok("msvc") {
        return Ok(());
    }
    let out = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default());
    let manifest = out.join("test-manifest.xml");
    fs::write(
        &manifest,
        r#"<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0"><dependency><dependentAssembly><assemblyIdentity type="win32" name="Microsoft.Windows.Common-Controls" version="6.0.0.0" processorArchitecture="*" publicKeyToken="6595b64144ccf1df" language="*"/></dependentAssembly></dependency></assembly>"#,
    )?;
    // `rustc-link-arg` reaches only this package's own linked targets (its unit-test binary),
    // never dependents; `-tests` would need a `tests/` target.
    println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
    println!("cargo:rustc-link-arg=/MANIFESTINPUT:{}", manifest.display());
    Ok(())
}
